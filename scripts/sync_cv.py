"""
Pull this site's content from the myCV repository.

- Talks, outreach and education: copied from myCV/data/ into _data/.
- Publications: downloaded from INSPIRE into assets/ref.bib, with the
  website-only extras from myCV/data/papers.yml (selected, code, slides, ...).
- Accent color: read from \\mycolor in myCV/personalinfo.tex into _config_cv.yml.

Nothing is written unless every input was read and the download succeeded, so
a failure leaves the previous outputs (and the live site) as they were.

Usage:
    python3 scripts/sync_cv.py              # reads ../myCV
    bundle exec jekyll serve --config _config.yml,_config_cv.yml
"""
import argparse
import os
import re
import sys
import urllib.error
import urllib.request
from typing import List, Optional

import yaml

SITE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INSPIRE_URL = (
    "https://inspirehep.net/api/literature?q=author:Alessandro.Santini.2"
    "&sort=mostrecent&size=100&format=bibtex"
)
DATA_FILES = ("talks.yml", "outreach.yml", "education.yml")
GENERATED = "Generated by scripts/sync_cv.py from myCV -- do not edit."


class SyncError(Exception):
    pass


def read_accent_color(personalinfo_tex: str) -> str:
    """
    The CV's accent color, e.g. "#0969da" for \\newcommand{\\mycolor}{0969da}.
    """
    match = re.search(r"\\newcommand\{\\mycolor\}\{([0-9A-Fa-f]{6})\}", personalinfo_tex)
    if not match:
        raise SyncError("no \\newcommand{\\mycolor}{RRGGBB} found in personalinfo.tex")
    return "#" + match.group(1)


def fetch_bibtex(url: str) -> str:
    """
    Download BibTeX; fail on a network error or an empty result.
    """
    try:
        request = urllib.request.Request(url, headers={"User-Agent": "asantini29.github.io sync"})
        with urllib.request.urlopen(request, timeout=60) as response:
            bib = response.read().decode("utf-8")
    except (OSError, ValueError) as err:
        raise SyncError("could not download publications from %s: %s" % (url, err))
    if not re.search(r"(?m)^@", bib):
        raise SyncError("no publications in the response from %s" % url)
    return bib


def _bibtex_value(value):
    return str(value).lower() if isinstance(value, bool) else str(value)


def transform_bibtex(bib: str, extras: List[dict]) -> str:
    """
    Adapt INSPIRE's BibTeX to this template: add the arxiv field the arXiv
    button reads, file preprints (no journal) under @unpublished, drop
    \\ensuremath (rendered verbatim otherwise), and add papers.yml extras.
    """
    extras_by_id = {str(extra.get("arxiv")): extra for extra in extras}
    unmatched = set(extras_by_id)
    out = []
    for chunk in re.split(r"(?m)^(?=@)", bib):
        if not chunk.startswith("@"):
            out.append(chunk)
            continue
        chunk = chunk.replace("\\ensuremath", "")
        first, rest = chunk.split("\n", 1)
        fields = []
        eprint = re.search(r'(?m)^\s*eprint\s*=\s*"([^"]+)"', rest)
        if eprint:
            arxiv = eprint.group(1)
            fields.append('arxiv = "%s"' % arxiv)
            extra = extras_by_id.get(arxiv)
            if extra:
                unmatched.discard(arxiv)
                fields += ['%s = "%s"' % (k, _bibtex_value(v)) for k, v in extra.items() if k != "arxiv"]
        if first.startswith("@article{") and not re.search(r"(?m)^\s*journal\s*=", rest):
            first = "@unpublished{" + first[len("@article{"):]
        out.append(first + "\n" + "".join("    %s,\n" % f for f in fields) + rest)
    if unmatched:
        raise SyncError(
            "papers.yml lists arXiv %s, which matches no paper on INSPIRE "
            '(check the number, and quote it: arxiv: "2507.06300")' % ", ".join(sorted(unmatched))
        )
    return "".join(out)


def _read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Pull this site's content from myCV.")
    parser.add_argument("--cv", default=os.path.join(SITE_DIR, "..", "myCV"),
                        help="path to the myCV repository (default: ../myCV)")
    parser.add_argument("--site", default=SITE_DIR, help="site root to write into")
    parser.add_argument("--inspire-url", default=INSPIRE_URL, help="BibTeX source")
    args = parser.parse_args(argv)

    try:
        data = {name: _read(os.path.join(args.cv, "data", name)) for name in DATA_FILES}
        papers = yaml.safe_load(_read(os.path.join(args.cv, "data", "papers.yml"))) or []
        color = read_accent_color(_read(os.path.join(args.cv, "personalinfo.tex")))
        bib = transform_bibtex(fetch_bibtex(args.inspire_url), papers)
    except (OSError, yaml.YAMLError, SyncError) as err:
        print("sync_cv.py: %s" % err, file=sys.stderr)
        return 1

    outputs = {os.path.join("_data", name): text for name, text in data.items()}
    outputs[os.path.join("assets", "ref.bib")] = "@comment{%s}\n\n%s" % (GENERATED, bib)
    outputs["_config_cv.yml"] = '# %s\naccent_color: "%s"\n' % (GENERATED, color)
    for relative, text in outputs.items():
        with open(os.path.join(args.site, relative), "w", encoding="utf-8") as f:
            f.write(text)

    count = len(re.findall(r"(?m)^@(?!comment)", bib))
    print("Synced from %s: %s, %d publications, accent %s"
          % (os.path.normpath(args.cv), ", ".join(DATA_FILES), count, color))
    return 0


if __name__ == "__main__":
    sys.exit(main())
